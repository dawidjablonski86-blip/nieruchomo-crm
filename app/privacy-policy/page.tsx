function renderPolicy(text: string) {
  const lines = text.split("\n");
  const elements: JSX.Element[] = [];
  let listBuffer: string[] = [];

  function flushList(key: string) {
    if (listBuffer.length > 0) {
      elements.push(
        <ul key={key} style={{ margin: "6px 0 14px", paddingLeft: 20, color: "#334155" }}>
          {listBuffer.map((item, i) => (
            <li key={i} style={{ marginBottom: 4, fontSize: 14 }}>{item}</li>
          ))}
        </ul>
      );
      listBuffer = [];
    }
  }

  lines.forEach((line, i) => {
    const trimmed = line.trim();

    if (trimmed.startsWith("* ")) {
      listBuffer.push(trimmed.slice(2));
      return;
    }
    flushList(`list-${i}`);

    if (trimmed === "---") {
      elements.push(<hr key={i} style={{ border: "none", borderTop: "1px solid #E2E8F0", margin: "24px 0" }} />);
    } else if (trimmed.startsWith("### ")) {
      elements.push(<h3 key={i} style={{ fontSize: 15, fontWeight: 700, marginTop: 16, marginBottom: 6 }}>{trimmed.slice(4)}</h3>);
    } else if (trimmed.startsWith("## ")) {
      elements.push(<h2 key={i} style={{ fontSize: 18, fontWeight: 700, marginTop: 24, marginBottom: 8 }}>{trimmed.slice(3)}</h2>);
    } else if (trimmed.startsWith("# ")) {
      elements.push(<h1 key={i} style={{ fontSize: 22, fontWeight: 700, marginTop: 10, marginBottom: 10 }}>{trimmed.slice(2)}</h1>);
    } else if (trimmed.length > 0) {
      elements.push(<p key={i} style={{ fontSize: 14, color: "#334155", lineHeight: 1.7, marginBottom: 10 }}>{trimmed}</p>);
    }
  });

  flushList("list-end");
  return elements;
}

